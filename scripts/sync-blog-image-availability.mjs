/**
 * Scan public/images/blog for uploaded webp files and write a small
 * availability module used by SEO / JSON-LD (avoid broken OG links).
 */
import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const blogDir = path.join(root, "public", "images", "blog");
const outFile = path.join(root, "src", "blog", "data", "available-images.js");

await fs.mkdir(blogDir, { recursive: true });

let files = [];
try {
  files = await fs.readdir(blogDir);
} catch {
  files = [];
}

const slugs = files
  .filter((name) => /\.webp$/i.test(name))
  .map((name) => name.replace(/\.webp$/i, ""))
  .filter(Boolean)
  .sort();

const body = `/* Auto-generated by scripts/sync-blog-image-availability.mjs — do not edit */
export const availableBlogImages = new Set(${JSON.stringify(slugs)});

export function isBlogImageAvailable(slug) {
  return typeof slug === "string" && availableBlogImages.has(slug);
}

export default availableBlogImages;
`;

await fs.writeFile(outFile, body, "utf8");
console.log(
  `Blog image availability: ${slugs.length} uploaded file(s) in public/images/blog`,
);
